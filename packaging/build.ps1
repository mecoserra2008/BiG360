<#
.SYNOPSIS  Reproducible build of the BiG Equity 360 Windows app (O3): portable folder, optional zip and installer.
.DESCRIPTION
  Output: packaging\out\BiG360\   (the app; what the installer installs and the portable zip contains)
      BiG360.exe / .vbs / .cmd     launchers (tray app, no console)       big360.ico, VERSION, .env (BIG360_DATA_DIR)
      runtime\                     Python 3.13 + the locked dependencies (requirements.lock.txt)
      backend\app, contracts, config, scripts, app_dist (built UI), docs\USER_GUIDE.md
  Data is never copied: the app uses BIG360_DATA_DIR (default: this project's data folder; the installer asks).

  Steps: 1 requirements.lock.txt from .venv (pip freeze)   2 icon   3 UI (npm run build:app)   4 app files
         5 runtime   6 launchers   7 .env   8 self-check   9 zip (-Zip)   10 installer (-Installer, Inno Setup 6)
         11 publish to an update folder (-PublishTo)

  Runtime modes
    copy  (default, offline) the base CPython 3.13 of .venv (pyvenv.cfg home) + .venv\Lib\site-packages: exactly the
          tested interpreter and packages; a full CPython install folder is relocatable.
    embed (network)  python.org embeddable zip (-PythonVersion) + pip install --target from requirements.lock.txt
          (wheels only). ~2 GB download: not on a metered connection / phone hotspot.
.EXAMPLE  .\packaging\build.ps1                       # portable folder (runtime reused if present: -CleanRuntime)
          .\packaging\build.ps1 -Zip -Installer       # + BiG360-<ver>-portable.zip + BiG360Setup-<ver>.exe
          .\packaging\build.ps1 -Runtime embed -CleanRuntime
          .\packaging\build.ps1 -Zip -PublishTo \\server\share\BiG360
#>
param(
    [ValidateSet("copy", "embed")][string]$Runtime = "copy",
    [string]$PythonVersion = "",
    [string]$Out = "",
    [string]$DataDir = "",
    [switch]$CleanRuntime,
    [switch]$SkipUi,
    [switch]$Zip,
    [switch]$Installer,
    [string]$PublishTo = ""
)
$ErrorActionPreference = "Stop"
$R = Split-Path $PSScriptRoot -Parent
if (-not $Out) { $Out = Join-Path $PSScriptRoot "out" }
$Stage = Join-Path $Out "BiG360"
$VenvPy = Join-Path $R ".venv\Scripts\python.exe"
$Ver = (Get-Content (Join-Path $R "VERSION") -Raw).Trim()
if (-not $DataDir) { $DataDir = Join-Path $R "data" }
New-Item -ItemType Directory -Force $Stage | Out-Null
function Step($m) { Write-Host "==> $m" -ForegroundColor DarkYellow }
function Robo($src, $dst, [string[]]$extra = @()) {
    & robocopy $src $dst /E /NFL /NDL /NJH /NJS /NP /R:2 /W:1 @extra | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy $src -> $dst failed ($LASTEXITCODE)" }
    $global:LASTEXITCODE = 0
}

# 1 ---------------------------------------------------------------- dependency lock
Step "requirements.lock.txt (pip freeze of .venv)"
$lock = Join-Path $PSScriptRoot "requirements.lock.txt"
$frozen = & $VenvPy -m pip freeze --exclude-editable 2>$null
if ($LASTEXITCODE -ne 0) { throw "pip freeze failed" }
$pyv = (& $VenvPy -c "import platform; print(platform.python_version())").Trim()
$hdr = @("# BiG Equity 360 $Ver - locked dependencies (pip freeze of .venv, Python $pyv, win_amd64). Generated by packaging\build.ps1.",
         "# Reinstall: python -m pip install -r packaging\requirements.lock.txt",
         "--extra-index-url https://download.pytorch.org/whl/cpu")
Set-Content -Path $lock -Encoding UTF8 -Value ($hdr + ($frozen | Where-Object { $_ -and $_ -notmatch "^(-e |#)" }))
if (-not $PythonVersion) { $PythonVersion = $pyv }

# 2 ---------------------------------------------------------------- icon
Step "icon (Logo-BIG.png -> big360.ico)"
& $VenvPy (Join-Path $PSScriptRoot "make_icon.py") | Out-Null

# 3 ---------------------------------------------------------------- UI
if (-not $SkipUi) {
    Step "frontend: npm run build:app"
    Push-Location (Join-Path $R "frontend")
    try { npm run build:app | Select-Object -Last 2; if ($LASTEXITCODE -ne 0) { throw "frontend build failed" } } finally { Pop-Location }
}
$ui = Join-Path $R "frontend\dist_app"
if (-not (Test-Path (Join-Path $ui "index.html"))) { throw "no built UI at $ui (run without -SkipUi)" }

# 4 ---------------------------------------------------------------- app files
Step "app files -> $Stage"
foreach ($d in "backend\app", "contracts", "config", "scripts") {
    $dst = Join-Path $Stage $d
    if (Test-Path $dst) { Remove-Item $dst -Recurse -Force }
    Robo (Join-Path $R $d) $dst @("/XD", "__pycache__", ".pytest_cache", ".ruff_cache", "/XF", "*.pyc", "*.log")
}
$appDist = Join-Path $Stage "app_dist"
if (Test-Path $appDist) { Remove-Item $appDist -Recurse -Force }
Robo $ui $appDist
New-Item -ItemType Directory -Force (Join-Path $Stage "docs"), (Join-Path $Stage "packaging") | Out-Null
Copy-Item (Join-Path $R "docs\USER_GUIDE.md") (Join-Path $Stage "docs") -Force
Copy-Item (Join-Path $R "VERSION"), (Join-Path $R "Logo-BIG.png") $Stage -Force
Copy-Item (Join-Path $PSScriptRoot "assets\big360.ico") $Stage -Force
Copy-Item $lock (Join-Path $Stage "packaging") -Force
Copy-Item (Join-Path $R "backend\requirements.txt") (Join-Path $Stage "backend") -Force
# never ship runtime state: a models_store junction / placeholder or logs left by a test run of the stage
$ms = Join-Path $Stage "models_store"
if (Test-Path $ms) {
    $it = Get-Item $ms -Force
    if ($it.Attributes -band [IO.FileAttributes]::ReparsePoint) { cmd /c rmdir "$ms" | Out-Null }
    elseif (-not (Get-ChildItem $ms -Force | Select-Object -First 1)) { Remove-Item $ms -Force }
    else { Write-Warning "$ms is a non-empty folder: left in place (not part of the build)" }
}
foreach ($junk in "data", "backend\.tmp") { $p = Join-Path $Stage $junk; if (Test-Path $p) { Write-Warning "stage contains $junk (left in place)" } }

# 5 ---------------------------------------------------------------- runtime
$rt = Join-Path $Stage "runtime"
if ($CleanRuntime -and (Test-Path $rt)) { Step "removing old runtime"; Remove-Item $rt -Recurse -Force }
if (-not (Test-Path (Join-Path $rt "pythonw.exe"))) {
    if ($Runtime -eq "copy") {
        $pyHome = ((Get-Content (Join-Path $R ".venv\pyvenv.cfg")) | Where-Object { $_ -match "^home\s*=" }) -replace "^home\s*=\s*", ""
        $pyHome = $pyHome.Trim()
        Step "runtime (copy): $pyHome + .venv site-packages"
        Robo $pyHome $rt @("/XD", (Join-Path $pyHome "Lib\site-packages"), (Join-Path $pyHome "Lib\test"), (Join-Path $pyHome "Scripts"),
                         (Join-Path $pyHome "Doc"), (Join-Path $pyHome "include"), (Join-Path $pyHome "libs"), "__pycache__")
        Robo (Join-Path $R ".venv\Lib\site-packages") (Join-Path $rt "Lib\site-packages") @("/XF", "_virtualenv.pth", "_virtualenv.py")
    } else {
        Step "runtime (embed): python-$PythonVersion-embed-amd64.zip + pip install -r requirements.lock.txt"
        $cache = Join-Path $PSScriptRoot "cache"
        New-Item -ItemType Directory -Force $cache, $rt | Out-Null
        $zipName = "python-$PythonVersion-embed-amd64.zip"
        $zipPath = Join-Path $cache $zipName
        if (-not (Test-Path $zipPath)) {
            Invoke-WebRequest "https://www.python.org/ftp/python/$PythonVersion/$zipName" -OutFile $zipPath
        }
        Expand-Archive $zipPath $rt -Force
        $pth = Get-ChildItem $rt -Filter "python*._pth" | Select-Object -First 1
        $tag = $pth.BaseName
        Set-Content -Path $pth.FullName -Encoding ASCII -Value @("$tag.zip", ".", "Lib\site-packages", "..\backend", "import site")
        & $VenvPy -m pip install --no-deps --only-binary=:all: --platform win_amd64 --python-version $PythonVersion `
            --implementation cp --target (Join-Path $rt "Lib\site-packages") -r $lock
        if ($LASTEXITCODE -ne 0) { throw "pip install --target failed" }
    }
} else { Step "runtime: reusing $rt (use -CleanRuntime to rebuild)" }

# 6 ---------------------------------------------------------------- launchers
Step "launchers"
& (Join-Path $PSScriptRoot "build_launcher.ps1") -OutDir $Stage

# 7 ---------------------------------------------------------------- .env (non-secret settings only)
$envFile = Join-Path $Stage ".env"
Set-Content -Path $envFile -Encoding UTF8 -Value @(
    "# BiG Equity 360 app settings (no API keys here: they live in Windows Credential Manager).",
    "# The installer rewrites this file with the data folder chosen during setup.",
    "BIG360_DATA_DIR=$DataDir")

# 8 ---------------------------------------------------------------- self-check
Step "self-check of the runtime"
Push-Location (Join-Path $Stage "backend")
$chk = & (Join-Path $rt "python.exe") -c "import sys, fastapi, uvicorn, duckdb, polars, pyarrow, apscheduler, filelock, PIL; import app.desktop.tray, app.api.static_ui, app.ops.supervisor; print(sys.version.split()[0], sys.prefix)" 2>&1
Pop-Location
Write-Host "   $chk"
if ($LASTEXITCODE -ne 0) { throw "runtime self-check failed" }
$size = [math]::Round(((Get-ChildItem $Stage -Recurse -File -ErrorAction SilentlyContinue | Measure-Object Length -Sum).Sum / 1GB), 2)
Write-Host "   $Stage : $size GB"

# 9 ---------------------------------------------------------------- zip
$artifacts = @()
if ($Zip) {
    $zipOut = Join-Path $Out "BiG360-$Ver-portable.zip"
    Step "zip -> $zipOut"
    if (Test-Path $zipOut) { Remove-Item $zipOut -Force }
    & tar.exe -a -c -f $zipOut -C $Out "BiG360"
    if ($LASTEXITCODE -ne 0) { throw "zip failed" }
    $artifacts += $zipOut
}

# 10 --------------------------------------------------------------- installer
if ($Installer) {
    $iscc = @("${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe", "$env:ProgramFiles\Inno Setup 6\ISCC.exe",
              "$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
    if (-not $iscc) {
        Write-Warning "Inno Setup 6 (ISCC.exe) not found: installer not built. Install Inno Setup 6, then re-run with -Installer. The portable folder / zip work without it."
    } else {
        Step "installer (Inno Setup): $iscc"
        & $iscc "/DAppVersion=$Ver" "/DSourceDir=$Stage" "/DDefaultDataDir=$DataDir" "/O$Out" (Join-Path $PSScriptRoot "installer\BiG360.iss")
        if ($LASTEXITCODE -ne 0) { throw "ISCC failed ($LASTEXITCODE)" }
        $artifacts += (Join-Path $Out "BiG360Setup-$Ver.exe")
    }
}

# 11 --------------------------------------------------------------- publish (update folder)
if ($PublishTo -and $artifacts.Count) {
    Step "publish -> $PublishTo"
    New-Item -ItemType Directory -Force $PublishTo | Out-Null
    foreach ($a in $artifacts) { Copy-Item $a $PublishTo -Force }
    $main = Split-Path ($artifacts | Sort-Object { if ($_ -like "*.exe") { 0 } else { 1 } } | Select-Object -First 1) -Leaf
    @{ version = $Ver; file = $main; notes = ""; built_at = (Get-Date).ToString("s") } | ConvertTo-Json |
        Set-Content -Path (Join-Path $PublishTo "latest.json") -Encoding UTF8
}
Step "done: $Stage"
