"""Price-level generators + the nightly `tech_levels` job (owner: technicals).

`build_levels(bars)` turns daily bars into a point-in-time LevelSet:

* static level *instances*  (key, price, start, end, anchor, ...): usable on bars [start, end) only — start is always
  after the information that defines the level is complete (no look-ahead);
* per-bar *series* (AVWAPs, 52w/ATH extremes, SMAs, round numbers): series[s, t] uses bars < t only.

Index n (one past the last bar) is the next session: instances with start <= n < end plus series[:, n] are the
levels active for tomorrow, which is what `snapshot()` / the tech_levels table hold. The same LevelSet drives the
event-study backtest (level_backtest.py), so live levels and backtested levels are generated by identical code.

Level families, see app/technicals/taxonomy.py:
  swing fractals (k=2,3,5,10 daily, k=2 weekly) · ZigZag(3 ATR) market structure HH/HL/LH/LL + BOS/CHoCH ·
  prior/current D/W/M/Q/Y open/high/low/close/mid + opening range · floor / Camarilla / Fibonacci pivots ·
  Fibonacci retracements/extensions of the last ZigZag leg · AVWAPs (YTD, QTD, swing high/low, last filing, 52w hi/lo) ·
  volume profile POC/VAH/VAL/HVN (6M, 1Y) · 52w high/low, all-time high · round numbers · SMA50/200 · unfilled gaps.
"""

