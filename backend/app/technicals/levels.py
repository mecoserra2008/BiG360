def snapshot(ls: LevelSet, b: Bars, band_k: float = 0.25, brk_b: float = 0.5, at: int | None = None) -> pl.DataFrame:
    """Levels active for the next session (index n), with touches / last touch / validity.

    `at` (optional, 1 <= at <= n): point-in-time view for the session at index `at` (the levels active after the
    close of bar at - 1, using bars < at only). Default = n (the live snapshot). Used by the Technicals v2
    walk-forward (app.techprob.history) so historical zones come from the identical code path.

    Returns a frame with: level_key, level_type, timeframe, family, price, anchor_date, known_from, swing_order,
    touches, last_touch, still_valid, structure_label, node_strength, distance_atr, distance_pct, side.
    """
    n = ls.n if at is None else int(min(max(at, 1), ls.n))
    close = float(b.c[n - 1])
    atr = float(ls.atr[n - 1]) if np.isfinite(ls.atr[n - 1]) else float(np.nanmean(b.h[max(0, n - 14):n] - b.l[max(0, n - 14):n]))
    m = (ls.start <= n) & (ls.end > n)
    idx = np.flatnonzero(m)
    touches, last, broken = K.touch_stats(b.h, b.l, b.c, ls.atr, ls.px[idx], ls.start[idx], ls.role[idx], n, band_k, brk_b)
    keys = ls.key[idx]
    gap_ids = {T.KEY_ID["gap_up@NA"], T.KEY_ID["gap_down@NA"]}
    is_gap = np.isin(keys, list(gap_ids))
    keep = ~(is_gap & (touches > 0))  # filled gaps are gone
    idx, keys, touches, last, broken = idx[keep], keys[keep], touches[keep], last[keep], broken[keep]
    rows_key = [T.KEY_BY_ID[k] for k in keys]
    df_static = {
        "level_key": rows_key,
        "price": ls.px[idx],
        "anchor_i": ls.anchor[idx],
        "start_i": ls.start[idx],
        "touches": touches,
        "last_i": last,
        "still_valid": ~broken,
        "label": ls.label[idx],
        "node_strength": ls.strength[idx],
    }
    # series values for the next session
    sp = ls.s_px[:, n] if ls.s_px.shape[0] else np.zeros(0)
    sa = ls.s_anchor[:, n] if ls.s_px.shape[0] else np.zeros(0, np.int64)
    ok = np.isfinite(sp) & (sp > 0)
    s_idx = np.flatnonzero(ok)
    t0 = max(1, n - 252)
    s_t, s_last = K.series_touch_stats(b.h, b.l, ls.atr, ls.s_px[s_idx], t0, n, band_k) if s_idx.size else (
        np.zeros(0, np.int64), np.zeros(0, np.int64))
    s_keys = [T.KEY_BY_ID[k] for k in ls.s_key[s_idx]]
    s_price = sp[s_idx]
    s_anchor = sa[s_idx].copy()
    # round numbers: anchor = last bar that traded through the level (else window start)
    for j, k in enumerate(s_keys):
        if k.startswith("round_"):
            pr = s_price[j]
            hit = np.flatnonzero((b.l[t0:n] <= pr) & (b.h[t0:n] >= pr))
            s_anchor[j] = t0 + hit[-1] if hit.size else t0
    s_valid = np.ones(s_idx.shape[0], dtype=bool)
    df_series = {
        "level_key": s_keys,
        "price": s_price,
        "anchor_i": s_anchor,
        "start_i": np.full(s_idx.shape[0], n, np.int64),
        "touches": s_t,
        "last_i": s_last,
        "still_valid": s_valid,
        "label": np.zeros(s_idx.shape[0], np.int64),
        "node_strength": np.full(s_idx.shape[0], np.nan),
    }
    df = pl.concat([pl.DataFrame(df_static), pl.DataFrame(df_series)], how="vertical_relaxed")
    if df.is_empty():
        return df
    dates = ls.dates
    dist_atr = (df["price"].to_numpy() - close) / atr if atr > 0 else np.zeros(df.height)
    dist_pct = df["price"].to_numpy() / close - 1.0
    tf = [T.split_key(k)[1] for k in df["level_key"]]
    lt = [T.split_key(k)[0] for k in df["level_key"]]
    fam = [T.FAMILY_OF_TYPE[t] for t in lt]
    order = [int(t.rsplit("_k", 1)[1]) if t.startswith("swing_") else None for t in lt]
    last_i = df["last_i"].to_numpy()
    df = df.with_columns(
        pl.Series("level_type", lt), pl.Series("timeframe", tf), pl.Series("family", fam),
        pl.Series("swing_order", order, dtype=pl.Int16),
        pl.Series("anchor_date", dates[np.clip(df["anchor_i"].to_numpy(), 0, n)]).cast(pl.Date),
        pl.Series("known_from", dates[np.clip(df["start_i"].to_numpy(), 0, n)]).cast(pl.Date),
        pl.Series("last_touch", np.where(last_i >= 0, dates[np.clip(last_i, 0, n)], np.datetime64("NaT", "D"))).cast(pl.Date),
        pl.Series("distance_atr", dist_atr), pl.Series("distance_pct", dist_pct),
        pl.Series("structure_label", [LABEL_NAME.get(int(x)) for x in df["label"]], dtype=pl.Utf8),
    )
    df = df.with_columns(
        pl.when(pl.col("price") < close).then(pl.lit("support")).otherwise(pl.lit("resistance")).alias("side"),
        pl.col("touches").cast(pl.Int16),
    )
    near = (pl.col("distance_atr").abs() <= SNAPSHOT_MAX_ATR) | (pl.col("distance_pct").abs() <= SNAPSHOT_MAX_PCT) | \
        pl.col("family").is_in(list(_ALWAYS_KEEP_FAMILIES))
    df = df.filter(near & pl.col("price").is_finite())
    # PK (level_key, anchor_date) must be unique: keep the instance nearest to price
    df = (df.with_columns(pl.col("distance_atr").abs().alias("_d")).sort("_d")
          .unique(subset=["level_key", "anchor_date"], keep="first").drop("_d", "anchor_i", "start_i", "last_i", "label"))
    return df.sort("price")


