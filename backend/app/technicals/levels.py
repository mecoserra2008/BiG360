def _stats_lookup(as_of: date) -> pl.DataFrame:
    """Latest level_type_stats snapshot on/before as_of (security rows + pool + universe rows)."""
    from app.core.storage import scan_table

    lf = scan_table("level_type_stats").filter(pl.col("as_of_date") <= as_of)
    last = lf.select(pl.col("as_of_date").max()).collect().item()
    if last is None:
        return pl.DataFrame(schema={"security_id": pl.Utf8, "level_key": pl.Utf8, "score": pl.Float64, "pool_key": pl.Utf8})
    return lf.filter(pl.col("as_of_date") == last).select("security_id", "level_key", "score", "pool_key").collect()


def attach_reliability(df: pl.DataFrame, stats: pl.DataFrame, security_id: str, pool_key: str) -> pl.DataFrame:
    """type_rank_score: ticker score, else (sector, region) pool score, else universe score, else 0.5."""
    if stats.is_empty():
        return df.with_columns(pl.lit(None, dtype=pl.Float64).alias("type_rank_score"))
    own = stats.filter(pl.col("security_id") == security_id).select("level_key", pl.col("score").alias("_s1"))
    pool = stats.filter(pl.col("security_id") == f"*{pool_key}").select("level_key", pl.col("score").alias("_s2"))
    uni = stats.filter(pl.col("security_id") == "*").select("level_key", pl.col("score").alias("_s3"))
    out = df.join(own, on="level_key", how="left").join(pool, on="level_key", how="left").join(uni, on="level_key", how="left")
    return out.with_columns(pl.coalesce("_s1", "_s2", "_s3").alias("type_rank_score")).drop("_s1", "_s2", "_s3")


def levels_for_security(b: Bars, stats: pl.DataFrame, as_of: date) -> pl.DataFrame:
    from .weights import level_weight_expr

    ls = build_levels(b)
    df = snapshot(ls, b)
    if df.is_empty():
        return df
    df = attach_reliability(df, stats, b.security_id, b.pool_key)
    df = df.with_columns(pl.lit(b.security_id).alias("security_id"), pl.lit(as_of).alias("as_of_date"))
    return df.with_columns(level_weight_expr(as_of).alias("weight"))


def _levels_task(b: Bars, stats: pl.DataFrame, as_of: date) -> pl.DataFrame | None:
    try:
        return levels_for_security(b, stats, as_of)
    except Exception as e:  # noqa: BLE001
        log.warning("tech_levels %s failed: %s", b.security_id, e)
        return None


def _levels_task_own(item: tuple[Bars, pl.DataFrame], shared: pl.DataFrame, as_of: date) -> pl.DataFrame | None:
    """`item` = (bars, this security's own level_type_stats rows); `shared` = pool + universe rows ('*...')."""
    b, own = item
    return _levels_task(b, pl.concat([own, shared], how="vertical_relaxed") if own.height else shared, as_of)


def split_stats(stats: pl.DataFrame, security_ids: list[str]) -> tuple[pl.DataFrame, dict[str, pl.DataFrame]]:
    """(pool + universe rows, {security_id: own rows}) for one batch. level_type_stats covers the whole priced
    universe (~3.5 M rows); shipping all of it to every worker chunk and filtering it per security does not scale."""
    if stats.is_empty():
        return stats, {}
    shared = stats.filter(pl.col("security_id").str.starts_with("*"))
    own = stats.filter(pl.col("security_id").is_in(security_ids))
    return shared, {str(k[0]): g for k, g in own.partition_by("security_id", as_dict=True).items()}


def month_end_retention(existing: pl.DataFrame, as_of: date) -> pl.DataFrame:
    """Keep rows of the last as_of_date of each past month (month-end snapshots); drop everything else."""
    if existing.is_empty():
        return existing
    ex = existing.filter(pl.col("as_of_date") < date(as_of.year, as_of.month, 1))
    if ex.is_empty():
        return ex
    ends = ex.group_by(pl.col("as_of_date").dt.truncate("1mo").alias("_m")).agg(pl.col("as_of_date").max().alias("_e"))
    return ex.filter(pl.col("as_of_date").is_in(ends["_e"].to_list()))


def month_end_dates(dates: list[date], as_of: date) -> list[date]:
    """The as_of_dates month_end_retention keeps: the last date of each month before as_of's month."""
    first = date(as_of.year, as_of.month, 1)
    ends: dict[tuple[int, int], date] = {}
    for d in dates:
        if d is not None and d < first:
            k = (d.year, d.month)
            ends[k] = max(ends.get(k, d), d)
    return sorted(ends.values())


def _stats_last(as_of: date) -> tuple[pl.LazyFrame | None, pl.DataFrame]:
    """(lazy own-row source, shared pool + universe rows) of the latest level_type_stats snapshot on/before as_of.
    A1 2026-11: the job no longer holds the whole snapshot (~3.5 M rows); each batch collects its own securities'
    rows (same rows split_stats would pick from the full frame)."""
    from app.core.storage import scan_table

    lf = scan_table("level_type_stats").filter(pl.col("as_of_date") <= as_of)
    last = lf.select(pl.col("as_of_date").max()).collect().item()
    empty = pl.DataFrame(schema={"security_id": pl.Utf8, "level_key": pl.Utf8, "score": pl.Float64, "pool_key": pl.Utf8})
    if last is None:
        return None, empty
    snap = lf.filter(pl.col("as_of_date") == last).select("security_id", "level_key", "score", "pool_key")
    shared = snap.filter(pl.col("security_id").str.starts_with("*")).collect(engine="streaming")
    return snap, shared


def _stats_own(snap: pl.LazyFrame | None, shared: pl.DataFrame, security_ids: list[str]) -> dict[str, pl.DataFrame]:
    if snap is None:
        return {}
    own = snap.filter(pl.col("security_id").is_in(security_ids)).collect(engine="streaming")
    return {str(k[0]): g for k, g in own.partition_by("security_id", as_dict=True).items()}


def run(ctx: JobContext) -> JobResult:
    """Nightly tech_levels: levels active for the session after ctx.as_of, for every security with recent prices.

    Memory (A1 2026-11, OOM at the 7 GB cap from 2026-11-03, the oom_params retry too): securities are processed in
    batches of `batch` and each batch's levels are written straight to a staging dir (app.core.lake_stream); the
    month-end snapshots kept from the current table (from November on: the whole 6.1 M-row October snapshot) are
    streamed into the stage, never loaded, and the stage replaces the table in one swap. Before, every batch's
    levels were held until the end, the old table was read back and the 12 M-row concatenation conformed and
    written in one piece, so a smaller `batch` / fewer `workers` could not bring the peak down. Peak memory is now
    one batch (price panel + pool workers), set by `batch` and `workers`."""
    from app.core.lake_stream import StagedWrite, distinct_values

    from .data import iter_bars, list_securities, load_ath_prior, load_earnings_dates, load_meta, load_price_panel, years_before
    from .parallel import pmap

    t0 = time.perf_counter()
    as_of = ctx.as_of
    source = str(ctx.params.get("source", "prices_daily"))
    tickers = ctx.params.get("tickers")
    win_start = years_before(as_of, float(ctx.params.get("years", 3.2)))
    sids = list(tickers) if tickers else list_securities(source, min_last_date=as_of - timedelta(days=14), since=win_start, min_bars=60)
    if not sids:
        return JobResult(status="success", message="no securities with recent prices")
    meta = load_meta(sids)
    earnings = load_earnings_dates(meta)
    snap, shared = _stats_last(as_of)
    empty = shared.head(0)
    batch = int(ctx.params.get("batch", 3000))
    workers = ctx.params.get("workers")
    cols = _contract_cols("tech_levels")
    stamp = pl.lit(datetime.now(UTC)).alias("computed_at")
    failed = levels_n = 0
    ok_ids: set[str] = set()
    with StagedWrite("tech_levels", ctx.settings) as sw:
        for i in range(0, len(sids), batch):
            ctx.check_cancelled()
            chunk = sids[i:i + batch]
            panel = load_price_panel(chunk, start=win_start, end=as_of, source=source)
            ath = load_ath_prior(chunk, win_start, source=source)
            bars = list(iter_bars(panel, meta, earnings, ath, min_bars=60))
            del panel
            own = _stats_own(snap, shared, [b.security_id for b in bars])
            res = pmap(partial(_levels_task_own, shared=shared, as_of=as_of), [(b, own.get(b.security_id, empty)) for b in bars],
                       workers=workers, cancel=ctx.check_cancelled)
            del bars, own
            failed += sum(r is None for r in res)
            frames = [r for r in res if r is not None and not r.is_empty()]
            del res
            if frames:
                out = pl.concat(frames, how="vertical_relaxed").with_columns(stamp)
                del frames
                sw.add(out.select([c for c in out.columns if c in cols]))
                ok_ids.update(out["security_id"].unique().to_list())
                levels_n += out.height
                del out
        if not sw.rows:
            return JobResult(status="failed" if failed else "success", entities_failed=failed, message="no levels produced")
        keep = [d for d in month_end_dates(distinct_values("tech_levels", "as_of_date", ctx.settings), as_of) if d != as_of]
        rows = sw.commit_overwrite(retain=pl.col("as_of_date").is_in(keep) if keep else None)
    ok = len(ok_ids)
    ctx.log.info("tech_levels: %d securities, %d levels in %.1fs (%d month-end snapshot rows kept)", ok, levels_n,
                 time.perf_counter() - t0, rows - levels_n)
    return JobResult(status="partial" if failed else "success", rows_written={"tech_levels": rows}, entities_ok=ok,
                     entities_failed=failed)


def _contract_cols(table: str) -> set[str]:
    from app.core.schema import get_contract

    return set(get_contract(table).column_names)
