@dataclass(frozen=True)
class LevelParams:
    atr_period: int = 14
    swing_age: tuple[tuple[int, int], ...] = ((2, 63), (3, 126), (5, 252), (10, 504))
    weekly_swing_age: int = 504
    zigzag_mult: float = 3.0
    ms_age: int = 252
    break_age: int = 126
    fib_age: int = 252
    gap_min_atr: float = 0.25
    gap_age: int = 252
    vp_bins: int = 60
    vp_step: int = 5
    vp_hvn: int = 3
    or_bars: tuple[tuple[str, int], ...] = (("W", 1), ("M", 5), ("Q", 10), ("Y", 20))
    ext_min_periods: int = 240


DEFAULT_PARAMS = LevelParams()


@dataclass
class LevelSet:
    n: int
    dates: np.ndarray                     # n+1 dates (last = next business day)
    atr: np.ndarray                       # n
    key: np.ndarray                       # static instances ...
    px: np.ndarray
    start: np.ndarray
    end: np.ndarray
    anchor: np.ndarray
    maxev: np.ndarray
    role: np.ndarray
    label: np.ndarray
    strength: np.ndarray
    s_key: np.ndarray                     # series ...
    s_px: np.ndarray                      # [S, n+1]
    s_anchor: np.ndarray                  # [S, n+1]
    zz: tuple = ()                        # (idx, px, dir, conf)
    breaks: tuple = ()                    # (bar, px, kind, dir, pivot_idx, trend_per_bar)
    extra: dict = field(default_factory=dict)

    @property
    def n_static(self) -> int:
        return int(self.px.shape[0])


class _Acc:
    """Accumulates static instances as array chunks."""

    def __init__(self) -> None:
        self.parts: list[tuple] = []

    def add(self, key, px, start, end, anchor, *, maxev=0, role=0, label=0, strength=np.nan) -> None:
        px = np.asarray(px, dtype=np.float64)
        m = px.shape[0]
        if m == 0:
            return

        def arr(x, dt):
            a = np.asarray(x, dtype=dt)
            return np.full(m, a, dtype=dt) if a.ndim == 0 else a

        self.parts.append((arr(key, np.int64), px, arr(start, np.int64), arr(end, np.int64), arr(anchor, np.int64),
                           arr(maxev, np.int64), arr(role, np.int64), arr(label, np.int64), arr(strength, np.float64)))

    def build(self):
        if not self.parts:
            e_i = np.zeros(0, np.int64)
            e_f = np.zeros(0, np.float64)
            return e_i, e_f, e_i, e_i, e_i, e_i, e_i, e_i, e_f
        cols = list(zip(*self.parts, strict=True))
        return tuple(np.concatenate(c) for c in cols)


def next_business_day(d: np.datetime64) -> np.datetime64:
    return np.busday_offset(d, 1, roll="forward")


def _period_ids(all_dates: np.ndarray, tf: str) -> np.ndarray:
    if tf == "D":
        return np.arange(all_dates.shape[0], dtype=np.int64)
    days = all_dates.astype("datetime64[D]").astype(np.int64)
    if tf == "W":
        return (days + 3) // 7
    months = all_dates.astype("datetime64[M]").astype(np.int64)
    if tf == "M":
        return months
    if tf == "Q":
        return months // 3
    if tf == "Y":
        return all_dates.astype("datetime64[Y]").astype(np.int64)
    raise ValueError(tf)


def _bounds(pid: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    starts = np.flatnonzero(np.r_[True, pid[1:] != pid[:-1]])
    ends = np.r_[starts[1:], pid.shape[0]]
    return starts.astype(np.int64), ends.astype(np.int64)


def _period_ohlc(o, h, l, c, starts, n):  # noqa: E741
    """OHLC of periods that contain real bars (starts < n). Returns arrays aligned to those periods."""
    sr = starts[starts < n]
    O = o[sr]
    H = np.maximum.reduceat(h, sr)
    L = np.minimum.reduceat(l, sr)
    last = np.r_[sr[1:], n] - 1
    C = c[last]
    return sr, O, H, L, C


def _kid(t: str, tf: str) -> int:
    return T.KEY_ID[f"{t}@{tf}"]


def _add_period_levels(acc: _Acc, b: Bars, all_dates: np.ndarray, p: LevelParams) -> None:
    n = b.n
    o, h, l, c = b.o, b.h, b.l, b.c  # noqa: E741
    h_ext = np.r_[h, np.nan]
    l_ext = np.r_[l, np.nan]
    or_bars = dict(p.or_bars)
    for tf in ("D", "W", "M", "Q", "Y"):
        starts, ends = _bounds(_period_ids(all_dates, tf))
        P = starts.shape[0]
        sr, O, H, L, C = _period_ohlc(o, h, l, c, starts, n)
        nr = sr.shape[0]  # periods with real bars are the first nr periods
        # prior-period levels: period q -> active in period q+1
        q = np.arange(nr)
        q = q[q + 1 < P]
        if q.size:
            st = starts[q + 1]
            en = ends[q + 1]
            an = starts[q]
            Oq, Hq, Lq, Cq = O[q], H[q], L[q], C[q]
            rng = Hq - Lq
            acc.add(_kid("prev_open", tf), Oq, st, en, an)
            acc.add(_kid("prev_high", tf), Hq, st, en, an, role=-1)
            acc.add(_kid("prev_low", tf), Lq, st, en, an, role=1)
            acc.add(_kid("prev_close", tf), Cq, st, en, an)
            acc.add(_kid("prev_mid", tf), (Hq + Lq) / 2.0, st, en, an)
            if tf != "D":
                P0 = (Hq + Lq + Cq) / 3.0
                acc.add(_kid("floor_p", tf), P0, st, en, an)
                acc.add(_kid("floor_r1", tf), 2 * P0 - Lq, st, en, an, role=-1)
                acc.add(_kid("floor_s1", tf), 2 * P0 - Hq, st, en, an, role=1)
                acc.add(_kid("floor_r2", tf), P0 + rng, st, en, an, role=-1)
                acc.add(_kid("floor_s2", tf), P0 - rng, st, en, an, role=1)
                acc.add(_kid("floor_r3", tf), Hq + 2 * (P0 - Lq), st, en, an, role=-1)
                acc.add(_kid("floor_s3", tf), Lq - 2 * (Hq - P0), st, en, an, role=1)
                acc.add(_kid("cam_h3", tf), Cq + 1.1 * rng / 4.0, st, en, an, role=-1)
                acc.add(_kid("cam_h4", tf), Cq + 1.1 * rng / 2.0, st, en, an, role=-1)
                with np.errstate(divide="ignore", invalid="ignore"):
                    h5 = np.where(Lq > 0, Hq / Lq * Cq, np.nan)
                acc.add(_kid("cam_h5", tf), h5, st, en, an, role=-1)
                acc.add(_kid("cam_l3", tf), Cq - 1.1 * rng / 4.0, st, en, an, role=1)
                acc.add(_kid("cam_l4", tf), Cq - 1.1 * rng / 2.0, st, en, an, role=1)
                acc.add(_kid("cam_l5", tf), Cq - (h5 - Cq), st, en, an, role=1)
                acc.add(_kid("fibp_r1", tf), P0 + 0.382 * rng, st, en, an, role=-1)
                acc.add(_kid("fibp_r2", tf), P0 + 0.618 * rng, st, en, an, role=-1)
                acc.add(_kid("fibp_r3", tf), P0 + 1.000 * rng, st, en, an, role=-1)
                acc.add(_kid("fibp_s1", tf), P0 - 0.382 * rng, st, en, an, role=1)
                acc.add(_kid("fibp_s2", tf), P0 - 0.618 * rng, st, en, an, role=1)
                acc.add(_kid("fibp_s3", tf), P0 - 1.000 * rng, st, en, an, role=1)
        if tf == "D":
            continue
        # current-period open: known after the first bar of the period
        q = np.arange(nr)
        st = starts[q] + 1
        en = ends[q]
        ok = st < en
        acc.add(_kid("cur_open", tf), O[ok], st[ok], en[ok], starts[q][ok])
        # opening range: first k bars of the period
        k = or_bars[tf]
        s0 = starts[q]
        ok = (s0 + k <= n) & (s0 + k < ends[q])
        if ok.any():
            s0 = s0[ok]
            idx = np.empty(2 * s0.shape[0], dtype=np.int64)
            idx[0::2] = s0
            idx[1::2] = s0 + k
            orh = np.fmax.reduceat(h_ext, idx)[0::2]
            orl = np.fmin.reduceat(l_ext, idx)[0::2]
            acc.add(_kid("or_high", tf), orh, s0 + k, ends[q][ok], s0, role=-1)
            acc.add(_kid("or_low", tf), orl, s0 + k, ends[q][ok], s0, role=1)


def _add_swings(acc: _Acc, b: Bars, all_dates: np.ndarray, p: LevelParams) -> dict:
    out = {}
    for k, age in p.swing_age:
        fh, fl = K.fractal_flags(b.h, b.l, k)
        ih = np.flatnonzero(fh)
        il = np.flatnonzero(fl)
        acc.add(_kid(f"swing_high_k{k}", "D"), b.h[ih], ih + k + 1, ih + k + 1 + age, ih, role=-1)
        acc.add(_kid(f"swing_low_k{k}", "D"), b.l[il], il + k + 1, il + k + 1 + age, il, role=1)
        out[k] = (ih, il)
    # weekly fractals (complete weeks only)
    starts, ends = _bounds(_period_ids(all_dates, "W"))
    P = starts.shape[0]
    sr = starts[starts < b.n]
    ncomplete = min(sr.shape[0], P - 1)
    if ncomplete >= 5:
        sw = sr[:ncomplete]
        WH = np.maximum.reduceat(b.h, sr)[:ncomplete]
        WL = np.minimum.reduceat(b.l, sr)[:ncomplete]
        for k in (2,):
            fh, fl = K.fractal_flags(WH, WL, k)
            for flags, arr, typ, role in ((fh, b.h, "swing_high_k2", -1), (fl, b.l, "swing_low_k2", 1)):
                qs = np.flatnonzero(flags)
                qs = qs[qs + k + 1 < P]
                if qs.size == 0:
                    continue
                st = starts[qs + k + 1]
                anchors = np.array([sw[q] + (np.argmax(arr[sw[q]:ends[q]]) if role == -1 else np.argmin(arr[sw[q]:ends[q]]))
                                    for q in qs], dtype=np.int64)
                px = (WH if role == -1 else WL)[qs]
                acc.add(_kid(typ, "W"), px, st, st + p.weekly_swing_age, anchors, role=role)
    return out


def _add_structure(acc: _Acc, b: Bars, atr: np.ndarray, p: LevelParams):
    pidx, ppx, pdir, pconf = K.zigzag(b.h, b.l, atr, p.zigzag_mult)
    labels = np.zeros(pidx.shape[0], np.int64)
    last_h = np.nan
    last_l = np.nan
    for j in range(pidx.shape[0]):
        if pdir[j] == 1:
            if not math.isnan(last_h):
                labels[j] = LABEL_CODE["HH"] if ppx[j] > last_h else LABEL_CODE["LH"]
            last_h = ppx[j]
        else:
            if not math.isnan(last_l):
                labels[j] = LABEL_CODE["HL"] if ppx[j] > last_l else LABEL_CODE["LL"]
            last_l = ppx[j]
    for code, typ in ((1, "ms_hh"), (2, "ms_hl"), (3, "ms_lh"), (4, "ms_ll")):
        m = labels == code
        if m.any():
            st = pconf[m] + 1
            role = -1 if code in (1, 3) else 1
            acc.add(_kid(typ, "NA"), ppx[m], st, st + p.ms_age, pidx[m], role=role, label=code)
    bb, bp, bk, bd, bi, trend = K.structure_breaks(b.c, pidx, ppx, pdir, pconf)
    for kind, typ in ((1, "ms_bos"), (2, "ms_choch")):
        m = bk == kind
        if m.any():
            st = bb[m] + 1
            acc.add(_kid(typ, "NA"), bp[m], st, st + p.break_age, bi[m], role=np.where(bd[m] == 1, 1, -1))
    # Fibonacci of each ZigZag leg A -> B, active from B's confirmation until the next pivot is confirmed
    if pidx.shape[0] >= 2:
        A = ppx[:-1]
        B = ppx[1:]
        st = pconf[1:] + 1
        nxt = np.r_[pconf[2:] + 1, np.iinfo(np.int64).max // 4]
        en = np.minimum(nxt, st + p.fib_age)
        an = pidx[1:]
        for r, typ in ((0.236, "fib_236"), (0.382, "fib_382"), (0.5, "fib_500"), (0.618, "fib_618"), (0.786, "fib_786")):
            acc.add(_kid(typ, "NA"), B - (B - A) * r, st, en, an)
        for e, typ in ((1.272, "fib_ext_1272"), (1.618, "fib_ext_1618")):
            acc.add(_kid(typ, "NA"), A + (B - A) * e, st, en, an)
    return (pidx, ppx, pdir, pconf, labels), (bb, bp, bk, bd, bi, trend)


def _add_gaps(acc: _Acc, b: Bars, atr: np.ndarray, p: LevelParams) -> None:
    n = b.n
    if n < 3:
        return
    g = np.arange(1, n)
    a = atr[g - 1]
    with np.errstate(invalid="ignore"):
        up = (b.l[g] - b.h[g - 1]) > p.gap_min_atr * a
        dn = (b.l[g - 1] - b.h[g]) > p.gap_min_atr * a
    gu = g[up]
    gd = g[dn]
    acc.add(_kid("gap_up", "NA"), b.h[gu - 1], gu + 1, gu + 1 + p.gap_age, gu, maxev=1, role=1)
    acc.add(_kid("gap_down", "NA"), b.l[gd - 1], gd + 1, gd + 1 + p.gap_age, gd, maxev=1, role=-1)


def _add_volume_profile(acc: _Acc, b: Bars, p: LevelParams) -> None:
    if not np.nansum(b.v) > 0:
        return
    for window, tag in ((252, "1y"), (126, "6m")):
        if b.n < window:
            continue
        code, px, st, en, sg, an = K.volume_profile_levels(b.h, b.l, b.v, window, p.vp_step, p.vp_bins, p.vp_hvn)
        names = {0: f"vp_poc_{tag}", 1: f"vp_vah_{tag}", 2: f"vp_val_{tag}", 3: f"vp_hvn_{tag}"}
        for cval, typ in names.items():
            if f"{typ}@NA" not in T.KEY_ID:
                continue
            m = code == cval
            if m.any():
                acc.add(_kid(typ, "NA"), px[m], st[m], en[m], an[m], strength=sg[m])


def _ffill_anchor(n1: int, known_at: np.ndarray, anchor: np.ndarray) -> np.ndarray:
    """anchor_at[t] = anchor of the latest event with known_at <= t (anchors must be non-decreasing in time)."""
    out = np.full(n1, -1, dtype=np.int64)
    ok = (known_at >= 0) & (known_at < n1)
    if ok.any():
        # several events may become known at the same t: keep the largest anchor
        np.maximum.at(out, known_at[ok], anchor[ok])
        out = np.maximum.accumulate(out)
    return out


def _avwap(cs: np.ndarray, cv: np.ndarray, anc: np.ndarray) -> np.ndarray:
    n1 = anc.shape[0]
    t = np.arange(n1)
    ok = (anc >= 0) & (anc < t)
    out = np.full(n1, np.nan)
    a = anc[ok]
    tt = t[ok]
    den = cv[tt] - cv[a]
    with np.errstate(divide="ignore", invalid="ignore"):
        val = (cs[tt] - cs[a]) / den
    out[ok] = np.where(den > 0, val, np.nan)
    return out


def _round_series(c: np.ndarray, n1: int):
    prev = np.full(n1, np.nan)
    prev[1:] = c
    with np.errstate(divide="ignore", invalid="ignore"):
        mag = np.power(10.0, np.floor(np.log10(prev)))
    out = []
    for step_mult, typ in ((0.5, "round_major"), (0.1, "round_minor")):
        step = mag * step_mult
        below = np.floor(prev / step + 1e-9) * step
        above = below + step
        out.append((typ, below))
        out.append((typ, above))
    return out


def _series(b: Bars, all_dates: np.ndarray, swings: dict, p: LevelParams):
    n = b.n
    n1 = n + 1
    tp = (b.h + b.l + b.c) / 3.0
    v = np.where(np.isfinite(b.v), b.v, 0.0)
    cs = np.r_[0.0, np.cumsum(tp * v)]
    cv = np.r_[0.0, np.cumsum(v)]
    keys: list[int] = []
    pxs: list[np.ndarray] = []
    ancs: list[np.ndarray] = []

    def add(typ: str, px: np.ndarray, anc: np.ndarray) -> None:
        keys.append(_kid(typ, "NA"))
        pxs.append(px.astype(np.float64))
        ancs.append(anc.astype(np.int64))

    has_vol = cv[-1] > 0
    for tf, typ in (("Y", "avwap_ytd"), ("Q", "avwap_qtd")):
        starts, _ = _bounds(_period_ids(all_dates, tf))
        pid_start = np.repeat(starts, np.diff(np.r_[starts, n1]))
        if has_vol:
            add(typ, _avwap(cs, cv, pid_start), pid_start)
    k5 = swings.get(5)
    if k5 is not None and has_vol:
        ih, il = k5
        for idx, typ in ((ih, "avwap_swing_high"), (il, "avwap_swing_low")):
            anc = _ffill_anchor(n1, idx + 5 + 1, idx)
            add(typ, _avwap(cs, cv, anc), anc)
    if b.earnings.size and has_vol:
        e = b.earnings[(b.earnings >= b.dates[0]) & (b.earnings <= b.dates[-1])]
        if e.size:
            ab = np.searchsorted(b.dates, e, side="left").astype(np.int64)
            anc = _ffill_anchor(n1, ab + 1, ab)
            add("avwap_earnings", _avwap(cs, cv, anc), anc)
    hv, ha = K.rolling_extreme_prior(b.h, 252, True, p.ext_min_periods)
    lv, la = K.rolling_extreme_prior(b.l, 252, False, p.ext_min_periods)
    add("high_52w", hv, ha)
    add("low_52w", lv, la)
    if has_vol:
        add("avwap_52w_high", _avwap(cs, cv, ha), ha)
        add("avwap_52w_low", _avwap(cs, cv, la), la)
    run = np.r_[-np.inf, np.maximum.accumulate(b.h)]
    run_arg = np.r_[0, _running_argmax(b.h)]
    prior = b.ath_prior if np.isfinite(b.ath_prior) else -np.inf
    ath = np.maximum(run, prior)
    ath_anc = np.where(run >= prior, run_arg, 0)
    ath[0] = np.nan if not np.isfinite(prior) else prior
    if not np.isfinite(prior):
        ath[: min(p.ext_min_periods, n1)] = np.nan  # too little history to call it an all-time high
    add("all_time_high", np.where(np.isfinite(ath), ath, np.nan), ath_anc)
    t = np.arange(n1)
    for w, typ in ((50, "sma_50"), (200, "sma_200")):
        add(typ, K.sma_prior(b.c, w), np.maximum(t - w, 0))
    for typ, px in _round_series(b.c, n1):
        add(typ, px, np.maximum(t - 1, 0))
    if not keys:
        return np.zeros(0, np.int64), np.zeros((0, n1)), np.zeros((0, n1), np.int64)
    return np.asarray(keys, np.int64), np.vstack(pxs), np.vstack(ancs)


def _running_argmax(x: np.ndarray) -> np.ndarray:
    run = np.maximum.accumulate(x)
    is_new = np.r_[True, x[1:] >= run[:-1]]
    idx = np.where(is_new, np.arange(x.shape[0]), 0)
    return np.maximum.accumulate(idx)


def build_levels(b: Bars, p: LevelParams = DEFAULT_PARAMS, atr: np.ndarray | None = None) -> LevelSet:
    """All level instances + series for the bars (point-in-time; see module docstring)."""
    n = b.n
    all_dates = np.r_[b.dates, next_business_day(b.dates[-1])].astype("datetime64[D]")
    if atr is None:
        atr = K.atr_wilder(b.h, b.l, b.c, p.atr_period)
    acc = _Acc()
    _add_period_levels(acc, b, all_dates, p)
    swings = _add_swings(acc, b, all_dates, p)
    zz, brk = _add_structure(acc, b, atr, p)
    _add_gaps(acc, b, atr, p)
    _add_volume_profile(acc, b, p)
    key, px, start, end, anchor, maxev, role, label, strength = acc.build()
    ok = np.isfinite(px) & (px > 0) & (start < end) & (start <= n)
    s_key, s_px, s_anchor = _series(b, all_dates, swings, p)
    return LevelSet(n=n, dates=all_dates, atr=atr, key=key[ok], px=px[ok], start=start[ok], end=end[ok],
                    anchor=anchor[ok], maxev=maxev[ok], role=role[ok], label=label[ok], strength=strength[ok],
                    s_key=s_key, s_px=s_px, s_anchor=s_anchor, zz=zz, breaks=brk)


