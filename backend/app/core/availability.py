"""Data-availability reasons: why a data point is missing (owner: completeness, docs/STARTUP_SYNC_PLAN.md section 3).

One vocabulary for the whole app. The startup sync engine (section 1) uses the dataset-level codes; the completeness
audit (app.qa.completeness) adds field-level codes. Every code maps onto a sync-engine code (`sync`), so the Data
Sync panel and the UI tooltips agree:

    fresh / due / not_yet_published / source_unavailable / no_source / needs_key / failed   (sync engine, section 1)
    mapping_gap      identifier or join not resolving (e.g. a FINRA symbol)            -> failed
    pipeline_bug     source has the data, our pipeline drops it (fix pending)          -> failed
    stale            source exists but the stored copy has not refreshed yet           -> due
    not_applicable   the field does not apply to this entity (bank KPI for an insurer)  -> fresh
    out_of_scope     computed only for a universe subset (fundamentals universe)       -> no_source
    suppressed       value withheld: failed a plausibility bound or a validation gate   -> fresh
    insufficient_data the inputs a score needs are missing for this entity (full-universe
                     scores 2026-10-30: composite needs >= 5 factors incl. 2 core ones)   -> no_source
    source_disallowed the source's robots.txt / terms disallow automated collection: switched off, data
                     ingested before the switch kept (A9 2026-11-07, docs/it/ROBOTS_COMPLIANCE.md)  -> no_source

contracts/field_availability.yaml (generated by `python -m app.qa.completeness --write`) holds the measured coverage
of every BQL field per universe x region and the region-level reason of its gaps; `field_reason` adds the per-entity
context (stale prices, universe membership, sanity flags) on top.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any

import yaml

from app.core.config import Settings, get_settings

#: code -> (sync-engine code, short label, default tooltip text)
REASONS: dict[str, tuple[str, str, str]] = {
    "fresh": ("fresh", "Up to date", "Up to date"),
    "due": ("due", "Update due", "Pending data refresh: the source has newer data"),
    "not_yet_published": ("not_yet_published", "Not published yet", "Not published yet"),
    "source_unavailable": ("source_unavailable", "Source unavailable", "Source temporarily unavailable; retrying"),
    "no_source": ("no_source", "No source", "No free source for this market"),
    "needs_key": ("needs_key", "Needs API key", "Needs an API key"),
    "failed": ("failed", "Update failed", "The last update failed; it is retried automatically"),
    "mapping_gap": ("failed", "Not matched", "Identifier not matched to the source record"),
    "pipeline_bug": ("failed", "Known data gap", "Known pipeline gap: fix pending"),
    "stale": ("due", "Pending refresh", "Pending data refresh"),
    "not_applicable": ("fresh", "Not applicable", "Not applicable to this company"),
    "out_of_scope": ("no_source", "Not covered", "Not computed for this company's universe yet"),
    "suppressed": ("fresh", "Withheld", "Value withheld: outside plausibility bounds"),
    "insufficient_data": ("no_source", "Insufficient data", "Not enough inputs to compute this score"),
    # COVERAGE_V3 A9 (2026-11-07): the source's robots.txt / terms do not allow automated collection -> switched off
    "source_disallowed": ("no_source", "Source not permitted",
                          "The source does not allow automated collection (robots.txt / terms); not fetched"),
}
SYNC_CODES = ("fresh", "due", "not_yet_published", "source_unavailable", "no_source", "needs_key", "failed")
YAML_NAME = "field_availability.yaml"

#: field groups whose values come from the fundamentals pipeline (ratios / valuation / scores / models)
FUNDAMENTAL_GROUPS = frozenset({"fundamental", "valuation", "score", "factor", "model", "sector_kpi"})
#: a security whose last bar is this many days older than its region's latest bar is treated as not trading
STALE_PX_DAYS = 7


@dataclass(frozen=True)
class Reason:
    code: str
    message: str
    next_expected: str | None = None
    detail: str | None = None

    def public(self) -> dict[str, Any]:
        sync, label, _ = REASONS.get(self.code, REASONS["pipeline_bug"])
        return {"code": self.code, "sync_code": sync, "label": label, "message": self.message,
                "next_expected": self.next_expected, "detail": self.detail}


def make(code: str, message: str | None = None, next_expected: str | None = None, detail: str | None = None) -> Reason:
    if code not in REASONS:
        raise ValueError(f"unknown availability code {code!r}")
    return Reason(code, message or REASONS[code][2], next_expected, detail)


# ------------------------------------------------------------------------------------------------ contract file


_cache: dict[str, tuple[float, dict[str, Any]]] = {}


def load(settings: Settings | None = None, path: Path | None = None) -> dict[str, Any]:
    """contracts/field_availability.yaml (re-read when the file changes); {} when absent."""
    p = path or (settings or get_settings()).contracts_dir / YAML_NAME
    try:
        mt = p.stat().st_mtime
    except OSError:
        return {}
    hit = _cache.get(str(p))
    if hit and hit[0] == mt:
        return hit[1]
    loader = getattr(yaml, "CSafeLoader", yaml.SafeLoader)  # ~0.2 s instead of ~1.5 s for the 300 KB file
    doc = yaml.load(p.read_text(encoding="utf-8"), Loader=loader) or {}  # noqa: S506 - safe loader
    _cache[str(p)] = (mt, doc)
    return doc


def field_entry(field: str, settings: Settings | None = None, doc: dict[str, Any] | None = None) -> dict[str, Any] | None:
    d = doc if doc is not None else load(settings)
    f = (d.get("fields") or {}).get(field)
    if f is None:
        alias = (d.get("aliases") or {}).get(field)
        f = (d.get("fields") or {}).get(alias) if alias else None
    return f


def rule_of(doc: dict[str, Any], rule_id: str | None) -> dict[str, Any] | None:
    return (doc.get("rules") or {}).get(rule_id) if rule_id else None


def region_reason(field: str, region: str | None, settings: Settings | None = None,
                  doc: dict[str, Any] | None = None) -> Reason | None:
    """The documented reason of a field's gaps in a region (None = the field is normally available there). Without
    a region (or for a region without a gap) the field's main rule is used only when no region is given."""
    d = doc if doc is not None else load(settings)
    f = field_entry(field, settings, d)
    if not f:
        return None
    regs = f.get("regions") or {}
    if region:
        if region not in regs:
            return None
        rid = regs[region].get("rule")
    else:
        rid = f.get("rule")
    r = rule_of(d, rid)
    if not r or r.get("reason") in (None, "fresh"):
        return None
    return make(r["reason"], r.get("note"), r.get("next_expected"), r.get("fix"))


def field_reason(field: str, ctx: dict[str, Any], settings: Settings | None = None,
                 doc: dict[str, Any] | None = None) -> Reason:
    """Why `field` is (or would be) missing for one security. ctx keys (all optional): region, security_type,
    px_date, region_px_date, in_fund_scope (bool), has_fundamentals (bool), flags (set of '<field>_flag' names set),
    group (field group, else from the contract file)."""
    f = field_entry(field, settings, doc) or {}
    group = ctx.get("group") or f.get("group")
    flags = ctx.get("flags") or set()
    # full-universe scores / ML (2026-10-30): the security's own explained gap comes first
    if group in ("score", "factor") and ctx.get("score_missing"):
        fac = field.split(".")[1] if field.startswith("f.") and field.count(".") >= 1 else None
        if fac and fac not in parse_missing(ctx["score_missing"])["factors"]:
            fac = None
        if fac or (group == "score" and ctx.get("score_null", True)):
            return make("insufficient_data", describe_missing(ctx["score_missing"], fac))
    if group == "model" and ctx.get("ml"):
        hz = next((h for h in ("1M", "3M", "6M") if field.lower().endswith(h.lower())), "3M")
        st = (ctx["ml"] or {}).get(hz)
        if st and st[0]:
            return make(st[0], st[1])
    if f"{field}_flag" in flags:
        return make("suppressed", f"Withheld: outside plausibility bounds ({_bound_text(field)})")
    px, rpx = _d(ctx.get("px_date")), _d(ctx.get("region_px_date"))
    if px and rpx and (rpx - px).days > STALE_PX_DAYS:
        return make("stale", f"No trades since {px.isoformat()} (suspended, delisted or not refreshed)")
    if group in FUNDAMENTAL_GROUPS and ctx.get("has_fundamentals") is False:
        rr = region_reason(field, ctx.get("region"), settings, doc)
        if rr is not None and rr.code in ("no_source", "needs_key", "source_unavailable"):
            return rr
        return make("out_of_scope", "No financial statements loaded for this company yet (outside the fundamentals "
                                    "universe)")
    if group in FUNDAMENTAL_GROUPS and ctx.get("in_fund_scope") is False and ctx.get("has_fundamentals"):
        return make("out_of_scope", "Statements are loaded, but ratios / valuation are computed for the analysis "
                                    "universe only (refresh pending)")
    rr = region_reason(field, ctx.get("region"), settings, doc)
    if (rr is not None and group in FUNDAMENTAL_GROUPS and ctx.get("has_fundamentals")
            and rr.code in ("no_source", "needs_key", "source_unavailable", "out_of_scope")):
        # the region-level reason explains companies WITHOUT statements; this one has them
        return make("not_applicable", "Not computable from the reported statements (an input is missing or the "
                                      "ratio is not meaningful, e.g. negative earnings)")
    if rr is not None:
        return rr
    return make("not_applicable", "Not reported for this company (the issuer does not disclose it, or it does not "
                                  "apply)")


FACTOR_LABELS = {"quality": "quality", "profitability": "profitability", "growth": "growth", "value": "value",
                 "balance_sheet": "balance sheet", "momentum": "momentum", "insider": "insider", "sentiment": "sentiment",
                 "macro": "macro", "moat": "moat"}
CAUSE_TEXT = {"no_statements": "no financial statements loaded", "stale_statements": "statements older than 400 days",
              "low_coverage": "fewer than 30 % of its metrics available", "no_market_cap": "no market capitalisation "
              "(shares outstanding unknown)", "no_prices": "no price history", "stale_prices": "no recent price (suspended, "
              "delisted or not refreshed)", "short_history": "price history shorter than 126 sessions",
              "no_moat": "no moat assessment (needs 5 years of statements)",
              "no_sector": "no industry classification (sector) for this listing"}


def parse_missing(missing: str | list[str] | None) -> dict[str, Any]:
    """scoring_full missing_inputs ('<factor>:<cause>', 'factors:n/5', 'core:n/2'; list or comma-joined) ->
    {'factors': {factor: cause}, 'n_factors': int | None, 'n_core': int | None}."""
    items = missing.split(",") if isinstance(missing, str) else list(missing or [])
    out: dict[str, Any] = {"factors": {}, "n_factors": None, "n_core": None}
    for it in items:
        k, _, v = str(it).partition(":")
        if k == "factors":
            out["n_factors"] = int(v.split("/")[0]) if v.split("/")[0].isdigit() else None
        elif k == "core":
            out["n_core"] = int(v.split("/")[0]) if v.split("/")[0].isdigit() else None
        elif k:
            out["factors"][k] = v
    return out


def describe_missing(missing: str | list[str] | None, factor: str | None = None) -> str:
    """Tooltip text of an insufficient_data reason (composite, or one factor when `factor` is given)."""
    m = parse_missing(missing)
    if factor:
        cause = m["factors"].get(factor)
        return (f"Not enough inputs for the {FACTOR_LABELS.get(factor, factor)} factor: "
                f"{CAUSE_TEXT.get(cause or '', cause or 'inputs missing')}")
    by_cause: dict[str, list[str]] = {}
    for f, c in m["factors"].items():
        by_cause.setdefault(c, []).append(FACTOR_LABELS.get(f, f))
    parts = [f"{', '.join(fs)}: {CAUSE_TEXT.get(c, c)}" for c, fs in by_cause.items()]
    head = "Not enough inputs for a composite score (needs 5 factor scores incl. 2 of quality / profitability / value / growth"
    if m["n_factors"] is not None and m["n_core"] is not None:
        head += f"; has {m['n_factors']} incl. {m['n_core']} core"
    return head + ")" + (". Missing: " + "; ".join(parts) if parts else "")


def _bound_text(field: str) -> str:
    if field in ("roic", "croic"):
        return "|value| > 200 % or invested capital below 5 % of total assets"
    return "sanity bound"


def _d(v: Any) -> date | None:
    if v is None:
        return None
    if isinstance(v, date):
        return v
    try:
        return date.fromisoformat(str(v)[:10])
    except ValueError:
        return None
