/**
 * Server persistence for the watchlist and alert rules (contract: /watchlists, /alerts).
 * The UI store stays the source for rendering; this module mirrors changes to the backend when it is
 * available and silently degrades to localStorage-only when the API is in mock mode, answers 501
 * (not implemented yet) or is unreachable.
 */
import type { CAlert, CAlertEvent, CSecurityRef, CWatchlist, CWatchlistDetail } from './contract'
import type { AlertEventView, AlertRule } from './types'
import { alertEventFromContract, alertFromContract, alertToContract, watchlistIds } from './adapters/crossSection'
import { ApiError } from './errors'
import { USE_MOCK, http } from './http'

const WATCHLIST_NAME = 'Default'

type State = 'unknown' | 'available' | 'unavailable'
let state: State = USE_MOCK ? 'unavailable' : 'unknown'
let watchlistId: string | null = null

/** 501 / network / 404-on-collection → treat the feature as not served by this backend. */
function degrade(err: unknown): null {
  if (err instanceof ApiError && (err.status === 501 || err.status === 0 || err.status === 404 || err.status === 405)) state = 'unavailable'
  return null
}

export const remoteAvailable = (): boolean => state === 'available'

/** Server id of the default watchlist (News Terminal watchlist_news alerts); null when the API is unavailable. */
export const defaultWatchlistId = (): Promise<string | null> => ensureWatchlist()

async function ensureWatchlist(): Promise<string | null> {
  if (state === 'unavailable') return null
  if (watchlistId) return watchlistId
  try {
    const lists = await http.get<CWatchlist[]>('/watchlists')
    const found = lists.find((l) => l.name === WATCHLIST_NAME) ?? (await http.post<CWatchlist>('/watchlists', { name: WATCHLIST_NAME, description: 'BiG Equity 360 default watchlist' }))
    watchlistId = found.watchlist_id
    state = 'available'
    return watchlistId
  } catch (e) {
    return degrade(e)
  }
}

const isSecurityId = (id: string) => /^S[0-9A-Z]{6,}$/.test(id)

/** Local ids may be tickers / mock ids (e.g. "ASML.AS") → resolve to live security ids via /search; drop unknowns. */
async function resolveLocalIds(ids: string[]): Promise<string[]> {
  const out: string[] = []
  for (const id of ids) {
    if (isSecurityId(id)) {
      out.push(id)
      continue
    }
    for (const q of [id, id.split('.')[0]]) {
      const rows = await http.get<CSecurityRef[]>('/search', { q, limit: 5 }).catch(() => [] as CSecurityRef[])
      const hit = rows.find((r) => r.ticker.toUpperCase() === q.toUpperCase())
      if (hit) {
        out.push(hit.security_id)
        break
      }
    }
  }
  return [...new Set(out)]
}

/** Ticker / name of the watchlist items from the last sync (display only: palette, rule table). */
export const watchlistNames: Record<string, { ticker: string; name: string }> = {}

/** Server ids merged with local ids (local-only items are pushed up). null = server unavailable. */
export async function syncWatchlist(localIds: string[]): Promise<string[] | null> {
  const wid = await ensureWatchlist()
  if (!wid) return null
  try {
    const detail = await http.get<CWatchlistDetail>(`/watchlists/${encodeURIComponent(wid)}`)
    for (const r of detail.rows) watchlistNames[r.security.security_id] = { ticker: r.security.ticker, name: r.security.name }
    const server = watchlistIds(detail)
    const local = await resolveLocalIds(localIds)
    const missing = local.filter((id) => !server.includes(id))
    await Promise.all(missing.map((id) => http.post(`/watchlists/${encodeURIComponent(wid)}/items`, { security_id: id }).catch(() => undefined)))
    return [...server, ...missing]
  } catch (e) {
    return degrade(e)
  }
}

export async function addWatchItem(id: string): Promise<void> {
  if (!isSecurityId(id)) return
  const wid = await ensureWatchlist()
  if (wid) await http.post(`/watchlists/${encodeURIComponent(wid)}/items`, { security_id: id }).catch(degrade)
}

export async function removeWatchItem(id: string): Promise<void> {
  const wid = await ensureWatchlist()
  if (wid) await http.del(`/watchlists/${encodeURIComponent(wid)}/items/${encodeURIComponent(id)}`).catch(degrade)
}

export async function loadAlerts(): Promise<AlertRule[] | null> {
  if (state === 'unavailable') return null
  try {
    const rows = await http.get<CAlert[]>('/alerts')
    state = 'available'
    // rules generated by a thesis (alerts.thesis_id, v1.26.0) are managed on the thesis page, not in the watchlist editor
    // ... and live news rules (watchlist_news / story_velocity, roadmap v3 N4) in the News Terminal
    return rows.filter((a) => !a.thesis_id && a.rule_type !== 'watchlist_news' && a.rule_type !== 'story_velocity').map(alertFromContract)
  } catch (e) {
    return degrade(e)
  }
}

/** The server refused a rule (HTTP 4xx other than "feature not served"): the message is shown to the user. */
export class AlertRejected extends Error {
  readonly status: number
  constructor(status: number, message: string) {
    super(message)
    this.name = 'AlertRejected'
    this.status = status
  }
}

/** 4xx validation errors are rejections (thrown); 501 / network / 404-405 degrade to local-only (null). */
function rejectOrDegrade(e: unknown): null {
  if (e instanceof ApiError && e.status >= 400 && e.status < 500 && ![404, 405].includes(e.status)) throw new AlertRejected(e.status, e.message || e.title || `HTTP ${e.status}`)
  return degrade(e)
}

/** Returns the server-created rule (with server id) or null when only local persistence is possible.
 *  Throws AlertRejected when the server refuses the rule (e.g. HTTP 400 invalid params). */
export async function createAlert(rule: Omit<AlertRule, 'id' | 'createdAt'>): Promise<AlertRule | null> {
  if (state === 'unavailable') return null
  try {
    const a = await http.post<CAlert>('/alerts', alertToContract(rule))
    state = 'available'
    return { ...alertFromContract(a), ticker: rule.ticker }
  } catch (e) {
    return rejectOrDegrade(e)
  }
}

export async function updateAlert(id: string, patch: Partial<AlertRule>): Promise<void> {
  if (state !== 'available') return
  const body: Record<string, unknown> = {}
  if (typeof patch.enabled === 'boolean') body.enabled = patch.enabled
  await http.patch(`/alerts/${encodeURIComponent(id)}`, body).catch(rejectOrDegrade)
}

export async function deleteAlert(id: string): Promise<void> {
  if (state !== 'available') return
  await http.del(`/alerts/${encodeURIComponent(id)}`).catch(rejectOrDegrade)
}

/** Fired alert events (macro rules fire as security_id "macro:<CC>"). */
export async function loadAlertEvents(limit = 100): Promise<AlertEventView[] | null> {
  if (USE_MOCK) return null
  try {
    const rows = await http.get<CAlertEvent[]>('/alerts/events', { limit })
    return rows.map(alertEventFromContract)
  } catch (e) {
    return degrade(e)
  }
}
